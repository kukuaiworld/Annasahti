import { Inject, Injectable, NotFoundException } from '@nestjs/common';
import { randomUUID } from 'crypto';
import {
  IIntelligenceRepository,
  INTELLIGENCE_REPOSITORY,
} from '../repositories/intelligence.repository.interface';
import {
  DELIVERY_TASK_REPOSITORY,
  IDeliveryTaskRepository,
} from '../../delivery/repositories/delivery-task.repository.interface';
import { SimulationRequestDto } from '../dto/simulation-request.dto';
import { EmergencyScenarioDto } from '../dto/emergency-scenario.dto';
import { CounterfactualRequestDto } from '../dto/counterfactual-request.dto';
import { OptimisationRequestDto } from '../dto/optimisation-request.dto';
import { DigitalTwinSimulationResult } from '../entities/simulation-result.entity';
import { EmergencyDisruptionScenario } from '../entities/emergency-scenario.entity';
import { CounterfactualImpactAnalysis } from '../entities/counterfactual-impact.entity';
import { NetworkOptimisationPlan } from '../entities/network-optimisation.entity';

@Injectable()
export class SimulationOrchestratorService {
  constructor(
    @Inject(INTELLIGENCE_REPOSITORY)
    private readonly repo: IIntelligenceRepository,
    @Inject(DELIVERY_TASK_REPOSITORY)
    private readonly taskRepo: IDeliveryTaskRepository,
  ) {}

  async runDigitalTwinSimulation(dto: SimulationRequestDto): Promise<DigitalTwinSimulationResult> {
    const id = randomUUID();
    const tasks = await this.taskRepo.findAvailableTasks();

    const baselineVolumeKg = tasks.reduce(
      (acc, t) => acc + (t.allocatedQuantity || 0),
      0,
    );
    const volumeMultiplier = 1 + (dto.surplusVolumeChangePercent || 0) / 100;
    const volunteerMultiplier = 1 + (dto.volunteerAvailabilityChangePercent || 0) / 100;

    const projectedSurplusKg = Number((baselineVolumeKg * volumeMultiplier).toFixed(2));
    const projectedSuccessRate = Math.min(
      0.95,
      Math.max(0.4, 0.85 * volunteerMultiplier),
    );

    const successfulDeliveries = Math.round(tasks.length * projectedSuccessRate);
    const unclaimedKg = Number((projectedSurplusKg * (1 - projectedSuccessRate)).toFixed(2));

    const result: DigitalTwinSimulationResult = {
      id,
      isSimulatedOutput: true,
      scenarioName: dto.notes || `Simulation: ${dto.scenarioType}`,
      scenarioType: dto.scenarioType,
      modelVersion: 'digital_twin_discrete_event_sim_v1.0.0',
      executedAt: new Date(),
      inputsAndAssumptions: {
        surplusVolumeChangePercent: dto.surplusVolumeChangePercent || 0,
        volunteerAvailabilityChangePercent: dto.volunteerAvailabilityChangePercent || 0,
        baselineVolumeKg,
        activeTasksEvaluated: tasks.length,
      },
      projectedMetrics: {
        estimatedSuccessfulDeliveries: successfulDeliveries,
        estimatedUnclaimedSurplusKg: unclaimedKg,
        projectedCapacityUtilisationPercent: Math.min(100, Math.round(75 * volumeMultiplier)),
        averageDeliveryDelayMinutes: dto.volunteerAvailabilityChangePercent && dto.volunteerAvailabilityChangePercent < 0 ? 45 : 18,
        totalTransportDistanceKm: Number((successfulDeliveries * 8.4).toFixed(1)),
        bottlenecksIdentified:
          unclaimedKg > 50
            ? ['Volunteer driver deficit in central sector during 17:00-19:00', 'Recipient cold storage limit approached']
            : ['Minor pickup delays observed during transit peaks'],
      },
      scenarioComparison: {
        baselineDeliveredKg: Number((baselineVolumeKg * 0.85).toFixed(2)),
        scenarioDeliveredKg: Number((projectedSurplusKg * projectedSuccessRate).toFixed(2)),
        differencePercentage: Math.round(((projectedSuccessRate - 0.85) / 0.85) * 100),
      },
      disclaimer:
        'NOTICE: This output is a simulated projection generated by the Digital Twin sandbox. It represents predictive modelling and must NEVER be reported as real operational impact.',
    };

    return this.repo.saveSimulation(result);
  }

  async getSimulation(id: string): Promise<DigitalTwinSimulationResult> {
    const sim = await this.repo.findSimulationById(id);
    if (!sim) {
      throw new NotFoundException(`Simulation with ID ${id} not found`);
    }
    return sim;
  }

  async createEmergencyScenario(dto: EmergencyScenarioDto): Promise<EmergencyDisruptionScenario> {
    const id = randomUUID();
    const tasks = await this.taskRepo.findAvailableTasks();

    const recommendations = tasks.slice(0, 3).map((t) => ({
      batchId: t.batchId,
      originalRecipientId: t.recipientOrganisationId,
      recommendedAlternativeRecipientId: 'emergency-hub-reallocation-001',
      foodCategory: t.foodCategory,
      quantity: t.allocatedQuantity,
      quantityUnit: t.quantityUnit,
      deadline: t.deliveryDeadline || new Date(Date.now() + 6 * 3600 * 1000),
      verifiedEligibilityReason: 'Recipient verified for human consumption with active intake quota',
      riskAssessment: 'Road detour required; estimated +15 minutes travel time',
      isHumanApproved: false,
    }));

    const scenario: EmergencyDisruptionScenario = {
      id,
      emergencyType: dto.emergencyType,
      reportedAt: new Date(),
      affectedGeographicZone: dto.affectedZone,
      affectedDonorsCount: Math.min(tasks.length, 2),
      affectedRecipientsCount: Math.min(tasks.length, 3),
      atRiskBatchesCount: tasks.length,
      recommendations,
      requiresHumanReview: true,
      status: 'pending_review',
    };

    return this.repo.saveEmergencyScenario(scenario);
  }

  async getEmergencyScenario(id: string): Promise<EmergencyDisruptionScenario> {
    const sc = await this.repo.findEmergencyScenarioById(id);
    if (!sc) {
      throw new NotFoundException(`Emergency scenario with ID ${id} not found`);
    }
    return sc;
  }

  async runCounterfactualAnalysis(dto: CounterfactualRequestDto): Promise<CounterfactualImpactAnalysis> {
    const id = randomUUID();
    const tasks = await this.taskRepo.findAvailableTasks();
    const totalConfirmedKg = tasks.reduce(
      (acc, t) => acc + (t.collectedQuantity || t.allocatedQuantity || 0),
      0,
    );

    // Default 65% counterfactual discard probability (i.e. 35% would have found alternative non-rescue routes)
    const baselineDiscardRate = dto.baselineDiscardRate ?? 0.65;
    const alternateChannelRate = Number((1 - baselineDiscardRate).toFixed(2));
    const estimatedDiscardAvoidedKg = Number((totalConfirmedKg * baselineDiscardRate).toFixed(2));
    const co2eFactor = 2.5; // 2.5 kg CO2e avoided per kg food rescued (FAO / WRI benchmark)

    const analysis: CounterfactualImpactAnalysis = {
      id,
      methodologyVersion: 'counterfactual_difference_in_differences_v1.0.0',
      analysisPeriodStart: dto.startDate ? new Date(dto.startDate) : new Date(Date.now() - 30 * 24 * 3600 * 1000),
      analysisPeriodEnd: dto.endDate ? new Date(dto.endDate) : new Date(),
      actualConfirmedDeliveriesKg: Number(totalConfirmedKg.toFixed(2)),
      counterfactualEstimates: {
        baselineUnclaimedDiscardRate: baselineDiscardRate,
        alternateChannelRedirectionRate: alternateChannelRate,
        estimatedDiscardAvoidedKg,
        estimatedAdditionalImpactKg: estimatedDiscardAvoidedKg,
        co2eAvoidedKgEstimated: Number((estimatedDiscardAvoidedKg * co2eFactor).toFixed(2)),
        emissionFactorUsedKgCo2PerKgFood: co2eFactor,
      },
      uncertaintyAndSensitivity: {
        confidenceLevel: 0.90,
        lowerBoundKg: Number((estimatedDiscardAvoidedKg * 0.85).toFixed(2)),
        upperBoundKg: Number((estimatedDiscardAvoidedKg * 1.15).toFixed(2)),
        keyAssumptions: [
          'Assumes 35% of surplus would have reached informal channels without FoodLoop.',
          'Assumes uniform methane landfill emission potential across mixed organic waste.',
        ],
        sensitivityNotes: 'Counterfactual additionality ranges from 55% to 75% depending on commercial food sector tier.',
      },
      attributionStatement:
        'Additional impact is calculated solely on surplus demonstrably diverted from disposal, avoiding 100% gross attribution claims.',
      calculatedAt: new Date(),
    };

    return this.repo.saveCounterfactual(analysis);
  }

  async getCounterfactualAnalysis(id: string): Promise<CounterfactualImpactAnalysis> {
    const cf = await this.repo.findCounterfactualById(id);
    if (!cf) {
      throw new NotFoundException(`Counterfactual analysis ${id} not found`);
    }
    return cf;
  }

  async runNetworkOptimisation(dto: OptimisationRequestDto): Promise<NetworkOptimisationPlan> {
    const id = randomUUID();
    const tasks = await this.taskRepo.findAvailableTasks();

    const matches = tasks.map((t, idx) => ({
      batchId: t.batchId,
      donorId: t.donorOrganisationId,
      recommendedRecipientId: t.recipientOrganisationId,
      allocatedQuantity: t.allocatedQuantity,
      quantityUnit: t.quantityUnit,
      estimatedTravelDistanceKm: 4.5 + idx * 1.2,
      priorityScore: 0.92 - idx * 0.05,
      selectionReasons: [
        'Recipient holds active capacity for specified food category',
        'Direct route minimizes transit exposure to under 30 minutes',
        'Species safety validation verified for destination',
      ],
      safetyEligibilityConfirmed: true,
      speciesCompatibilityConfirmed: true,
    }));

    const totalKg = tasks.reduce((acc, t) => acc + (t.allocatedQuantity || 0), 0);

    const plan: NetworkOptimisationPlan = {
      id,
      algorithm: 'bipartite_min_cost_flow_baseline_v1',
      generatedAt: new Date(),
      objectiveFunction: dto.objectiveStrategy || 'maximize_redistribution_min_distance',
      totalBatchesEvaluated: tasks.length,
      totalRecipientsEvaluated: tasks.length,
      recommendedMatches: matches,
      metrics: {
        totalRedistributedKg: totalKg,
        estimatedTotalDistanceKm: Number((matches.length * 6.5).toFixed(1)),
        capacityUtilisationPercent: 88,
      },
      humanReviewed: false,
    };

    return this.repo.saveOptimisationPlan(plan);
  }

  async getOptimisationPlan(id: string): Promise<NetworkOptimisationPlan> {
    const plan = await this.repo.findOptimisationPlanById(id);
    if (!plan) {
      throw new NotFoundException(`Optimisation plan ${id} not found`);
    }
    return plan;
  }
}
